def _levels(pairs: list[tuple[str, str]]) -> list[PriceLevel]:
    return [(Decimal(price), Decimal(size)) for price, size in pairs]


def _signed_crc32(text: str) -> int:
    crc = zlib.crc32(text.encode("ascii"))
    return crc - 0x1_0000_0000 if crc >= 0x8000_0000 else crc


def test_bitfinex_checksum_matches_reference_vectors() -> None:
    """Documented example plus three states captured from the live venue."""
    assert (
        bitfinex_checksum(_levels(DOCUMENTED_BIDS), _levels(DOCUMENTED_ASKS))
        == DOCUMENTED_CHECKSUM
    ), f"Bitfinex's documented example must hash {DOCUMENTED_TEXT}"

    book = OrderBook()
    observed: list[int] = []
    for frame in LIVE_FRAMES.strip().splitlines():
        data = json.loads(frame)
        payload = data[1]
        if payload == "cs":
            bids, asks = book.top(25)
            observed.append(bitfinex_checksum(bids, asks))
            continue
        if payload == "hb":
            continue
        if isinstance(payload[0], list):
            book.apply_snapshot(
                [
                    (Decimal(str(price)), Decimal(str(abs(amount))))
                    for price, _, amount in payload
                    if amount > 0
                ],
                [
                    (Decimal(str(price)), Decimal(str(abs(amount))))
                    for price, _, amount in payload
                    if amount < 0
                ],
            )
            continue
        price, count, amount = payload
        book.apply_delta(
            "bid" if amount > 0 else "ask",
            Decimal(str(price)),
            Decimal("0") if count == 0 else Decimal(str(abs(amount))),
        )
    assert observed == LIVE_EXPECTED_CHECKS
    assert len(observed) == 3


def test_js_number_format() -> None:
    """Numbers render the way JavaScript's ``Number.prototype.toString`` does."""
    cases = {
        "0": "0",
        "-0": "0",
        "100": "100",
        "0.5": "0.5",
        "0.50": "0.5",
        "0.0001": "0.0001",
        "0.00001": "0.00001",
        "0.000001": "0.000001",
        "0.0000001": "1e-7",
        "0.000000015": "1.5e-8",
        "0.0000012345": "0.0000012345",
        "123456789.12345678": "123456789.12345678",
        "1234567890123456789012": "1.2345678901234568e+21",
        "1e20": "100000000000000000000",
        "1e21": "1e+21",
        "6.02e23": "6.02e+23",
        "-1.25": "-1.25",
        "81106": "81106",
        "0.00436386": "0.00436386",
    }
    for text, expected in cases.items():
        assert js_number(Decimal(text)) == expected, text


def test_js_number_rounds_through_float64() -> None:
    """The venue hashes the float64 digits, not the text it received."""
    assert js_number(Decimal("0.1000000000000000055511151231257827")) == "0.1"
    assert js_number(Decimal("1.1000000000000001")) == "1.1"
    assert js_number(Decimal("9007199254740993")) == "9007199254740992"


def test_short_book_hashes_only_the_levels_it_has() -> None:
    """A book with fewer than 25 levels per side has no placeholders."""
    assert bitfinex_checksum(_levels([("6000", "1")]), _levels([("6100", "3")])) == _signed_crc32(
        "6000:1:6100:-3"
    )
    assert bitfinex_checksum([], []) == 0


def test_ask_amounts_are_negative() -> None:
    """Ask sizes are hashed with their venue sign; a positive ask never matches."""
    assert bitfinex_checksum(
        _levels(DOCUMENTED_BIDS), _levels(DOCUMENTED_ASKS)
    ) == _signed_crc32("6000:1:6100:-3:5900:2:6200:-4")
    assert bitfinex_checksum(
        _levels(DOCUMENTED_BIDS), _levels(DOCUMENTED_ASKS)
    ) != _signed_crc32("6000:1:6100:3:5900:2:6200:4")


def test_bid_and_ask_levels_interleave_by_rank() -> None:
    """Ranks alternate bid/ask; hashing all bids then all asks never matches."""
    computed = bitfinex_checksum(_levels(DOCUMENTED_BIDS), _levels(DOCUMENTED_ASKS))
    assert computed == _signed_crc32(DOCUMENTED_TEXT)
    all_bids_then_all_asks = _signed_crc32("6000:1:5900:2:6100:-3:6200:-4")
    assert computed != all_bids_then_all_asks


def test_only_the_top_twenty_five_levels_per_side_are_hashed() -> None:
    """The digest covers the top 25 levels; deeper levels are ignored."""
    bids = _levels(DOCUMENTED_BIDS) + [
        (Decimal(5000 - index), Decimal("1")) for index in range(30)
    ]
    asks = _levels(DOCUMENTED_ASKS) + [
        (Decimal(7000 + index), Decimal("1")) for index in range(30)
    ]
    assert bitfinex_checksum(bids, asks) == bitfinex_checksum(bids[:25], asks[:25])
    assert bitfinex_checksum(bids[:25], asks[:25]) != bitfinex_checksum(bids[:24], asks[:24])


def test_checksum_is_a_signed_32_bit_integer() -> None:
    """Half of the live checksums are negative; an unsigned compare never matches."""
    negative = [value for value in LIVE_EXPECTED_CHECKS if value < 0]
    assert negative, "the live vectors must include a negative checksum"
    for value in LIVE_EXPECTED_CHECKS:
        assert -0x8000_0000 <= value < 0x8000_0000


@pytest.mark.parametrize("value", ["1e-7", "1.5e-8", "1e+21"])
def test_exponent_form_is_never_zero_padded(value: str) -> None:
    rendered = js_number(Decimal(value))
    assert "e-0" not in rendered and "e+0" not in rendered
