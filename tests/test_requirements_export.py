"""Keep ``dashboard/requirements.txt`` in sync with ``uv.lock`` (issue #83).

Streamlit Community Cloud installs the first dependency file it finds next to
the entrypoint, so ``dashboard/requirements.txt`` is what the hosted app uses.
It is generated by ``make requirements``; this test fails when the lockfile
moves ahead of the committed export.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parents[1]
_REQUIREMENTS = _ROOT / "dashboard" / "requirements.txt"

_EXPORT_COMMAND = (
    "uv",
    "export",
    "--frozen",
    "--no-default-groups",
    "--group",
    "dashboard",
    "--no-hashes",
    "--no-header",
)


@pytest.mark.skipif(shutil.which("uv") is None, reason="uv is not on PATH")
def test_requirements_export_matches_the_lockfile(tmp_path: Path) -> None:
    out = tmp_path / "requirements.txt"
    subprocess.run(
        [*_EXPORT_COMMAND, "-o", str(out)],
        cwd=_ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    assert out.read_text(encoding="utf-8") == _REQUIREMENTS.read_text(encoding="utf-8")


def test_requirements_keep_the_hosted_install_small() -> None:
    lines = _REQUIREMENTS.read_text(encoding="utf-8").splitlines()
    assert "-e ." in lines
    assert any(line.startswith("streamlit==") for line in lines)
    assert not any(line.startswith(("dagster", "pytest", "ruff", "mypy")) for line in lines)
